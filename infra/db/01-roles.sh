#!/bin/sh
# Creates the least-privilege role used by the API at runtime.
# The POSTGRES_USER (owner) is used only for migrations.
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE ${DB_API_USER} LOGIN PASSWORD '${DB_API_PASSWORD}';
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${DB_API_USER};
GRANT USAGE ON SCHEMA public TO ${DB_API_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${DB_API_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO ${DB_API_USER};
SQL
